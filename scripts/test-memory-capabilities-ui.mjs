import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { startConsoleFixture } from './console-ui-fixture.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fixture = await startConsoleFixture();
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, reducedMotion: 'reduce' });
const failures = [];
page.on('pageerror', error => failures.push(error.message));
page.on('console', message => { if (message.type() === 'error') failures.push(message.text()); });
try {
  await page.goto(fixture.url);
  await page.locator('#mainNav [data-view="capabilities"]').click();
  await page.locator('[data-configure-capability="tts"]').click();
  await page.locator('#capability-tts-selected').waitFor();
  assert.equal(await page.locator('.capability-form').count(), 4);
  assert.equal(await page.locator('#capability-tts-selected').inputValue(), 'volcengine:S_demoVoice');
  assert.equal(await page.locator('#capability-tts-python').isVisible(), false);
  assert.equal(await page.locator('#capability-vision-base').isVisible(), false);
  assert.match(await page.locator('#capability-tts-help').innerText(), /已有 Key/);
  await page.getByRole('button', { name: '关闭能力设置' }).click();
  await page.locator('[data-configure-capability="vision"]').click();
  await page.locator('#capability-vision-selected').selectOption('siliconflow:Qwen/Qwen3.5-4B');
  const saved = page.waitForResponse(response => response.url().endsWith('/api/capabilities') && response.request().method() === 'POST');
  await page.locator('[data-capability="vision"] button[type="submit"]').click();
  assert.equal((await saved).status(), 200);
  await page.waitForFunction(() => document.getElementById('capabilityDialog').open === false);
  assert.equal(await page.locator('#capability-vision-selected').inputValue(), 'siliconflow:Qwen/Qwen3.5-4B');
  await page.locator('#addServiceForCapability').click();
  await page.locator('#serviceCapability').selectOption('vision');
  await page.locator('#serviceName').fill('我的备用识图');
  await page.locator('#serviceEndpoint').fill('https://custom-ui.example/v1');
  await page.locator('#serviceModel').fill('custom/vision_model:v1');
  await page.locator('#serviceKey').fill('fixture-service-secret');
  await page.locator('#serviceSave').click();
  await page.waitForFunction(() => document.getElementById('serviceManager').open === false);
  assert.equal(await page.locator('#capability-vision-selected').inputValue(), 'service:fixture-service-1');
  assert.equal(await page.locator('#serviceKey').inputValue(), '');
  await page.locator('[data-edit-service="fixture-service-1"]').click();
  assert.equal(await page.locator('#serviceKey').inputValue(), '');
  assert.equal(await page.locator('#serviceTemplate').isDisabled(), false);
  assert.equal(await page.locator('#serviceEndpoint').inputValue(), 'https://custom-ui.example/v1/chat/completions');
  await page.locator('#serviceReset').click();
  const artifacts = process.env.QQ_BRIDGE_UI_ARTIFACTS;
  if (artifacts) { await mkdir(artifacts, { recursive: true }); await page.screenshot({ path: `${artifacts}/capabilities.png`, fullPage: true, animations: 'disabled' }); }
  await page.locator('#mainNav [data-view="memory"]').click();
  assert.equal(await page.locator('[data-memory-choice="long-term"]').isVisible(), true);
  assert.equal(await page.locator('#memoryImport').isDisabled(), true);
  await page.locator('[data-memory-choice="long-term"]').click();
  await page.waitForFunction(() => document.getElementById('memorySettingsMessage').textContent.includes('已保存'));
  await page.locator('#memorySessionSelect option[value="private:100001"]').waitFor({ state: 'attached' });
  await page.locator('#memorySessionSelect').selectOption('private:100001');
  await page.locator('#v2MemoryOutput').getByText('共同经历 · 周末计划', { exact: true }).waitFor();
  page.once('dialog', dialog => dialog.accept('一起讨论阅读安排，已完成'));
  const edited = page.waitForResponse(response => response.url().endsWith('/api/socialV2/memory-update') && response.request().method() === 'POST');
  await page.locator('#v2MemoryOutput button[data-action="edit"]').click();
  assert.equal((await edited).status(), 200);
  if (artifacts) await page.locator('#section-memory').screenshot({ path: `${artifacts}/memory-modes.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), true);
  await page.getByText('更多设置与操作', { exact: true }).click();
  await page.getByText('列表里没有对象？输入 QQ 号或群号', { exact: true }).click();
  await page.locator('#memoryManualId').fill('987654321');
  await page.locator('#memoryManualLoad').click();
  assert.equal(await page.locator('#v2MemoryKey').inputValue(), 'private:987654321');
  assert.equal(await page.locator('#memorySessionSelect').inputValue(), 'private:987654321');
  if (artifacts) await page.screenshot({ path: `${artifacts}/memory-mobile.png`, fullPage: true, animations: 'disabled' });
  await page.locator('#mainNav [data-view="capabilities"]').evaluate(button => button.click());
  await page.locator('[data-configure-capability="tts"]').click();
  await page.locator('#capability-tts-selected').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), true);
  if (artifacts) await page.screenshot({ path: `${artifacts}/capabilities-mobile.png`, fullPage: true, animations: 'disabled' });
} finally {
  await browser.close(); await fixture.close();
}
assert.deepEqual(failures, []);
console.log('PASS: independent memory navigation and conversation selection, four visual capability selectors, save/reload, memory mode switching, long-term event rendering, no browser errors');
